export type Locale = 'ja' | 'ko'
const MESSAGES: Record<Locale, Record<MessageKey, string>> = { ja, ko }
const LOCALE_KEY = 'covershift.locale'

function initialLocale(): Locale {
  try {
    const v = localStorage.getItem(LOCALE_KEY)
    if (v === 'ja' || v === 'ko') return v
  } catch {
    /* 저장소가 막혀 있으면 기본값 */
  }
  return 'ja'
}

export const locale = ref<Locale>(initialLocale())

export function setLocale(next: Locale) {
  locale.value = next
  try {
    localStorage.setItem(LOCALE_KEY, next)
  } catch {
    /* 무시 */
  }
  if (typeof document !== 'undefined') document.documentElement.lang = next
}

export type Params = Record<string, string | number>

function fill(template: string, params?: Params): string {
  if (!params) return template
  return template.replace(/\{(\w+)\}/g, (m, k: string) => (k in params ? String(params[k]) : m))
}

/** 글자 하나. locale 을 읽으므로 템플릿 안에서 부르면 언어를 바꿀 때 다시 그려진다. */
export function t(key: MessageKey, params?: Params): string {
  return fill(MESSAGES[locale.value][key] ?? ja[key], params)
}

/** 동적인 키(상태 · 코드 이름 등). 없으면 fallback. */
export function tk(key: string, fallback: string, params?: Params): string {
  const table = MESSAGES[locale.value] as Record<string, string>
  const v = table[key]
  return v === undefined ? fallback : fill(v, params)
}

export function hasKey(key: string): boolean {
  return key in MESSAGES[locale.value]
}

// ---------------------------------------------------------------- 날짜 · 시점 표시

export function weekdayLabel(w: number): string {
  return tk(`weekday.${w}`, String(w))
}

export function monthLabel(targetMonth: string): string {
  return t('fmt.month', { y: Number(targetMonth.slice(0, 4)), m: Number(targetMonth.slice(5, 7)) })
}

export function dateLabel(date: string, withWeekday = true): string {
  const m = Number(date.slice(5, 7))
  const d = Number(date.slice(8, 10))
  if (!withWeekday) return t('fmt.md', { m, d })
  const js = new Date(`${date}T00:00:00Z`).getUTCDay()
  return t('fmt.mdw', { m, d, w: weekdayLabel(js === 0 ? 7 : js) })
}

export function dateTimeLabel(iso: string | null | undefined): string {
  if (!iso) return '—'
  const d = new Date(iso)
  if (Number.isNaN(d.getTime())) return iso
  return new Intl.DateTimeFormat(locale.value === 'ja' ? 'ja-JP' : 'ko-KR', {
    year: 'numeric',
    month: '2-digit',
    day: '2-digit',
    hour: '2-digit',
    minute: '2-digit',
  }).format(d)
}
